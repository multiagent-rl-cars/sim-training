"""Read-only source and installed-runtime integrity; never import the simulator."""

import base64
import hashlib
import importlib.metadata
import importlib.util
import json
import re
import subprocess
import tomllib
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Any, Literal


@dataclass(frozen=True)
class CheckoutIdentity:
    """Actual checkout state, not a claim derived from a dependency lock."""

    commit: str
    branch: str
    status_porcelain: str


@dataclass(frozen=True)
class ExperimentIdentity:
    source: dict[str, Any]
    isaaclab_runtime: "IsaacLabRuntimeIdentity"


@dataclass(frozen=True)
class IsaacLabRuntimeIdentity:
    """Installed bundle bytes, distinct from a Git checkout or GPU-runtime proof."""

    distribution: str
    version: str
    package_root: str
    files_verified: int
    content_sha256: str


def inspect_isaaclab_runtime(root: Path | None = None) -> IsaacLabRuntimeIdentity:
    """Verify the locked wheel's installed package tree without launching Kit.

    RECORD is installer metadata, not an independent signature: this detects
    missing, edited, redirected, or additional package files, not an attacker
    rewriting both the files and RECORD. GPU execution remains a separate gate.
    """
    root = root or Path(__file__).resolve().parents[2]
    lock = tomllib.loads((root / "uv.lock").read_text())
    versions = {item["version"] for item in lock["package"] if item["name"] == "isaaclab"}
    if len(versions) != 1:
        raise ValueError("The root lock must select exactly one Isaac Lab bundle version")
    distribution = importlib.metadata.distribution("isaaclab")
    if distribution.version != next(iter(versions)):
        raise ValueError("Installed Isaac Lab version differs from the root lock")
    files = distribution.files
    if not files:
        raise ValueError("Isaac Lab distribution has no installed file RECORD")
    installation_root = Path(str(distribution.locate_file(""))).resolve(strict=True)
    package_root = installation_root / "isaaclab"
    if package_root.resolve() != package_root or not package_root.is_dir():
        raise ValueError("Isaac Lab bundle directory is missing or redirected")
    specification = importlib.util.find_spec("isaaclab")
    if (
        specification is None
        or specification.origin is None
        or Path(specification.origin).resolve() != package_root / "__init__.py"
    ):
        raise ValueError("Isaac Lab import is shadowed or does not select the installed bundle")

    verified: dict[str, str] = {}
    for entry in files:
        relative = str(entry)
        if not relative.startswith("isaaclab/"):
            continue
        # Bytecode generated by Python is not part of the published wheel.
        if "__pycache__" in entry.parts and entry.suffix == ".pyc":
            continue
        if (
            ".." in entry.parts
            or "\\" in relative
            or str(PurePosixPath(relative)) != relative
            or relative in verified
        ):
            raise ValueError("Isaac Lab RECORD contains an invalid or duplicate package path")
        target = installation_root.joinpath(*entry.parts)
        if target.resolve() != target or not target.is_file():
            raise ValueError(f"Isaac Lab package file is missing or redirected: {relative}")
        if entry.hash is None or entry.hash.mode != "sha256":
            raise ValueError(f"Isaac Lab package file has no SHA-256 RECORD hash: {relative}")
        digest = hashlib.sha256(target.read_bytes()).digest()
        if base64.urlsafe_b64encode(digest).rstrip(b"=").decode() != entry.hash.value:
            raise ValueError(f"Isaac Lab package RECORD hash mismatch: {relative}")
        verified[relative] = digest.hex()

    required = {
        "isaaclab/__init__.py",
        "isaaclab/apps/isaaclab.python.headless.kit",
        "isaaclab/apps/isaaclab.python.headless.rendering.kit",
        "isaaclab/source/isaaclab/isaaclab/app/app_launcher.py",
        *(
            f"isaaclab/source/{package}/config/extension.toml"
            for package in ("isaaclab", "isaaclab_assets", "isaaclab_tasks", "isaaclab_rl")
        ),
    }
    if not required.issubset(verified):
        raise ValueError("Isaac Lab bundle lacks required extension metadata or app resources")
    for target in package_root.rglob("*"):
        if target.is_symlink():
            raise ValueError("Isaac Lab bundle contains a symlink")
        if "__pycache__" in target.parts and target.suffix == ".pyc":
            continue
        if not target.is_file() and not target.is_dir():
            raise ValueError("Isaac Lab bundle contains a special file")
        if target.is_file() and str(target.relative_to(package_root.parent)) not in verified:
            raise ValueError("Isaac Lab bundle contains an unrecorded package file")
    identity = json.dumps(verified, sort_keys=True, separators=(",", ":")).encode()
    return IsaacLabRuntimeIdentity(
        distribution="isaaclab",
        version=distribution.version,
        package_root=str(package_root),
        files_verified=len(verified),
        content_sha256=hashlib.sha256(identity).hexdigest(),
    )


def verify_experiment_identity(
    root: Path,
    run_directory: Path,
    mode: Literal["train", "start", "end"],
    resolved_config: Mapping[str, object],
) -> ExperimentIdentity:
    """Validate source/runtime identity before Kit starts.

    Evaluations use the training manifest, not a freshly recaptured source
    manifest. Exact recipe matching is intentional for matched before/after
    evaluation; evaluating changed recipes needs a separate workflow.
    """
    if mode not in ("train", "start", "end"):
        raise ValueError("Unsupported experiment phase")
    training_manifest = None
    if mode == "train":
        source = json.loads((root / "outputs/source-provenance.json").read_text())
    else:
        training_manifest = json.loads((run_directory / "manifest.json").read_text())
        if resolved_config != training_manifest["config"]:
            raise ValueError("Evaluation recipe differs from the training manifest")
        source = training_manifest["source"]
    verify_source_files(root, source["files_sha256"])
    runtime = inspect_isaaclab_runtime(root)
    if training_manifest is not None:
        saved_runtime = training_manifest.get("isaaclab_runtime")
        if saved_runtime is None:
            raise ValueError(
                "Training used a legacy checkout runtime; evaluate it with its frozen environment"
            )
        if any(
            saved_runtime.get(field) != getattr(runtime, field)
            for field in ("distribution", "version", "content_sha256")
        ):
            raise ValueError("Evaluation Isaac Lab runtime differs from the training manifest")
    return ExperimentIdentity(source, runtime)


def inspect_checkout(directory: Path) -> CheckoutIdentity:
    """Inspect exactly this Git checkout, never silently use a parent repository.

    Command failures propagate: unavailable identity must not look like a clean
    runtime. Remote URLs, Git configuration, and credentials are not collected.
    """
    directory = directory.resolve(strict=True)

    def git(*arguments: str) -> str:
        return subprocess.check_output(
            ["git", "-C", str(directory), *arguments],
            text=True,
            stderr=subprocess.PIPE,
            timeout=10,
        )

    if Path(git("rev-parse", "--show-toplevel").strip()).resolve() != directory:
        raise ValueError("Expected a Git checkout root, not a directory inside another checkout")
    return CheckoutIdentity(
        commit=git("rev-parse", "HEAD").strip(),
        branch=git("branch", "--show-current").strip(),
        status_porcelain=git("status", "--porcelain", "--untracked-files=all"),
    )


def verify_source_files(root: Path, expected: Mapping[str, str]) -> None:
    """Check every manifest file before an expensive launch.

    This verifies listed source bytes, not unlisted assets, installed packages,
    or the absence of extra files. Reject symlinks and noncanonical relative
    paths so a manifest cannot read outside its copied source tree.
    """
    root = root.resolve(strict=True)
    if not expected:
        raise ValueError("Source manifest contains no files")
    for relative, digest in expected.items():
        if not isinstance(relative, str) or not isinstance(digest, str):
            raise ValueError("Source manifest paths and SHA-256 digests must be strings")
        path = PurePosixPath(relative)
        if (
            not relative
            or path.is_absolute()
            or ".." in path.parts
            or str(path) != relative
            or "\\" in relative
            or not re.fullmatch(r"[0-9a-f]{64}", digest)
        ):
            raise ValueError("Source manifest contains an invalid path or SHA-256 digest")
        target = root.joinpath(*path.parts)
        if target.resolve() != target:
            raise ValueError(f"Source manifest contains a symlink: {relative}")
        if not target.is_file():
            raise ValueError(f"Source manifest file is missing or not a regular file: {relative}")
        actual = hashlib.sha256(target.read_bytes()).hexdigest()
        if actual != digest:
            raise ValueError(f"Source manifest hash mismatch: {relative}")
